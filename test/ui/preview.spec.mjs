import { test, expect } from '@playwright/test'
import { mkdir } from 'node:fs/promises'

const panelOf = page => page.locator('[data-panel="prompt-craft"]')
async function craft(page) {
  await page.locator('.pc-btn-root').click()
  await expect(panelOf(page)).toHaveAttribute('data-phase', 'ready')
}
async function geometry(page) {
  return page.evaluate(() => {
    const panel = document.querySelector('[data-panel="prompt-craft"]')
    const body = panel.querySelector('.pc-panel-body')
    const footer = panel.querySelector('.pc-panel-foot')
    const rect = panel.getBoundingClientRect()
    return {
      left: rect.left, right: rect.right, top: rect.top, bottom: rect.bottom,
      viewportWidth: innerWidth, viewportHeight: innerHeight,
      horizontalOverflow: document.documentElement.scrollWidth > innerWidth,
      bodyOverflow: body.scrollWidth > body.clientWidth,
      nestedScroll: [...panel.querySelectorAll('.pc-card-text')].some(node => /auto|scroll/.test(getComputedStyle(node).overflowY)),
      footerBottom: footer.getBoundingClientRect().bottom,
    }
  })
}
for (const theme of ['light', 'dark']) for (const width of [390, 768, 1440]) {
  for (const scenario of ['short', 'long', 'links', 'attachments', 'questions']) {
    test(`${theme} ${width}px ${scenario}: readable layout and reachable actions`, async ({ page }) => {
      const errors = []
      page.on('pageerror', error => errors.push(error.message))
      await page.setViewportSize({ width, height: 900 })
      await page.goto(`/?theme=${theme}&scenario=${scenario}&delay=10`)
      await craft(page)
      const box = await geometry(page)
      expect(box.left).toBeGreaterThanOrEqual(11)
      expect(box.right).toBeLessThanOrEqual(width - 11)
      expect(box.top).toBeGreaterThanOrEqual(11)
      expect(box.bottom).toBeLessThanOrEqual(box.viewportHeight - 11)
      expect(box.horizontalOverflow).toBe(false)
      expect(box.bodyOverflow).toBe(false)
      expect(box.nestedScroll).toBe(false)
      expect(box.footerBottom).toBeLessThanOrEqual(box.bottom)
      if (scenario === 'questions') {
        await expect(panelOf(page)).toHaveAttribute('data-status', 'needs_input')
        await expect(page.locator('.pc-card')).toHaveCount(0)
        await page.getByRole('button', { name: '按已有信息继续', exact: true }).click()
        await expect(panelOf(page)).toHaveAttribute('data-status', 'ready')
      }
      await expect(page.getByRole('button', { name: '应用结果', exact: true })).toBeVisible()
      const before = await page.locator('.pc-card-text').last().textContent()
      await page.getByRole('button', { name: '对照原文', exact: true }).click()
      await expect(page.locator('.pc-original')).toBeVisible()
      const after = await page.locator('.pc-card-text').last().textContent()
      expect(after).toBe(before)
      if (width === 390) await expect(page.locator('.pc-btn-root-label')).toBeHidden()
      expect(errors).toEqual([])
    })
  }
}

test('expanded reading, focus trap, Escape and focus restoration', async ({ page }) => {
  await page.goto('/?scenario=long&delay=10')
  await craft(page)
  const expand = page.getByRole('button', { name: '展开阅读', exact: true })
  await expand.click()
  const panel = panelOf(page)
  await expect(panel).toHaveAttribute('role', 'dialog')
  await expect(panel).toHaveAttribute('data-reading', 'expanded')
  expect(await panel.evaluate(node => node.contains(document.activeElement))).toBe(true)
  const actions = panel.getByRole('button')
  await actions.last().focus()
  await page.keyboard.press('Tab')
  await expect(actions.first()).toBeFocused()
  await page.keyboard.press('Shift+Tab')
  await expect(actions.last()).toBeFocused()
  await page.locator('.lab-draft').evaluate(node => node.focus())
  expect(await panel.evaluate(node => node.contains(document.activeElement))).toBe(true)
  await page.keyboard.press('Escape')
  await expect(panel).toHaveAttribute('data-reading', 'compact')
  await expect(page.getByRole('button', { name: '展开阅读', exact: true })).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(panel).toHaveCount(0)
  await expect(page.locator('.pc-btn-root')).toBeFocused()
})

test('hero layout, keyboard-sized viewport, resizing and composer changes', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 600 })
  await page.goto('/?layout=hero&scenario=long&delay=10')
  await craft(page)
  await expect(panelOf(page)).toHaveAttribute('data-reading', 'expanded')
  await page.setViewportSize({ width: 768, height: 320 })
  await expect.poll(async () => (await geometry(page)).top).toBeGreaterThanOrEqual(11)
  let box = await geometry(page)
  expect(box.top).toBeGreaterThanOrEqual(11)
  expect(box.bottom).toBeLessThanOrEqual(309)
  await page.keyboard.press('Escape')
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.evaluate(() => window.preview.setHero(false))
  await page.locator('.lab-draft').evaluate(node => { node.style.height = '180px' })
  await expect.poll(async () => {
    const panel = await panelOf(page).boundingBox()
    const composer = await page.locator('[data-composer-card]').boundingBox()
    return Math.round(composer.y - panel.y - panel.height)
  }).toBe(10)
  box = await geometry(page)
  expect(box.top).toBeGreaterThanOrEqual(11)
})

