test('regenerate, cancel, failure, copy, stale draft, apply and undo', async ({ page, context }) => {
  await context.grantPermissions(['clipboard-read', 'clipboard-write'])
  await page.goto('/?delay=10')
  await craft(page)
  const candidate = await page.locator('.pc-card-text').textContent()
  await page.evaluate(() => window.preview.setDelay(30000))
  await page.locator('.pc-btn-root').click()
  await expect(page.locator('.pc-card-text')).toHaveText(candidate)
  await expect(page.getByRole('button', { name: '应用结果', exact: true })).toBeDisabled()
  await page.getByRole('button', { name: '取消', exact: true }).last().click()
  await expect(panelOf(page)).toHaveAttribute('data-phase', 'ready')
  await page.evaluate(() => { window.preview.setDelay(10); window.preview.failNext() })
  await page.locator('.pc-btn-root').click()
  await expect(page.getByRole('alert')).toContainText('本次生成未完成')
  await expect(page.locator('.pc-card-text')).toHaveText(candidate)
  await page.getByRole('button', { name: '重试', exact: true }).click()
  await expect(page.getByRole('alert')).toHaveCount(0)
  await page.getByRole('button', { name: '复制', exact: true }).click()
  await expect(page.getByRole('button', { name: '已复制', exact: true })).toBeVisible()
  expect(await page.evaluate(() => navigator.clipboard.readText())).toBe(candidate)
  await page.locator('.lab-draft').fill('已经改变的草稿')
  await expect(page.getByRole('button', { name: '草稿已改，重新生成', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '草稿已改，重新生成', exact: true }).click()
  await expect(panelOf(page)).toHaveAttribute('data-phase', 'ready')
  await page.getByRole('button', { name: '应用结果', exact: true }).click()
  await expect(page.locator('.lab-draft')).toHaveValue(candidate)
  await expect(panelOf(page)).toHaveCount(0)
  await page.locator('.lab-draft').focus()
  await page.keyboard.press('Control+z')
  await expect(page.locator('.lab-draft')).toHaveValue('已经改变的草稿')
})

